use crate::support::in_memory_source_tree::NotHeld;
use crap4rust::coverage_io::coverage_failure::CoverageFailure;
use crap4rust::coverage_io::export::Export;
use crap4rust::coverage_io::export_chunk::ExportChunk;
use crap4rust::coverage_io::export_function::ExportFunction;
use crap4rust::invocation::package_context::PackageContext;
use crap4rust::traits::coverage_source::CoverageSource;

pub fn export_of(chunks: Vec<Vec<ExportFunction>>) -> Export {
    Export {
        data: chunks
            .into_iter()
            .map(|functions| ExportChunk { functions })
            .collect(),
    }
}

pub fn exported_function(filenames: &[&str], regions: &[&[u64]]) -> ExportFunction {
    ExportFunction {
        filenames: filenames.iter().map(|name| String::from(*name)).collect(),
        regions: regions.iter().map(|region| region.to_vec()).collect(),
    }
}

// The coverage export every core test reads, held in memory rather than
// generated by cargo llvm-cov and read from a file.
pub struct InMemoryCoverageSource {
    export: Option<Export>,
}

impl InMemoryCoverageSource {
    pub fn new(export: Export) -> Self {
        Self {
            export: Some(export),
        }
    }

    pub fn failing() -> Self {
        Self { export: None }
    }
}

impl CoverageSource for InMemoryCoverageSource {
    fn export(&self, _packages: &[PackageContext]) -> Result<Export, CoverageFailure> {
        self.export.clone().ok_or_else(|| CoverageFailure {
            cause: Box::new(NotHeld),
        })
    }
}
